# Dynamic simulator
# ------------------------------------------------------------------------------


class WellSimulator:
    """
    Dynamic simulator of a single naturally flowing oil well.

    Interface required by the challenge::

        Q, WHP, FLP, BHP = simulator.step(choke_position)

    One call to :meth:`step` advances the plant by one control interval
    (Ts = 1 hour).
    """

    Ts: float = 1.0  # control interval [h]

    def __init__(
        self,
        u0: float = 30.0,
        params: WellParameters | None = None,
        noise: bool = True,
        seed: int | None = 42,
        enforce_ramp: bool = True,
        disturbances: list | None = None,
    ):
        # deep-copied so a time-varying reservoir pressure in one simulator
        # never leaks into another
        self.p = replace(params or WellParameters())
        self.disturbances = list(disturbances or [])
        self.noise = noise
        self.enforce_ramp = enforce_ramp
        self.rng = np.random.default_rng(seed)

        self.u = float(np.clip(u0, self.p.u_min, self.p.u_max))
        ss = steady_state(self.u, self.p)
        self.Q = ss["Q"] * (1.0 - self.p.water_cut)
        self.WHP, self.FLP, self.BHP = ss["WHP"], ss["FLP"], ss["BHP"]
        self.WHT, self.AP = ss["WHT"], ss["AP"]

        # First-order hold state for the small FLP transport delay
        self._flp_delay_buffer = [self.FLP]
        self.t = 0.0
        self.history: list[dict] = []
        self._log()

    # -- internals ------------------------------------------------------------

    def _lag(self, y: float, y_target: float, tau: float) -> float:
        """Advance one first-order lag by one sample (exact ZOH discretisation)."""
        a = np.exp(-self.Ts / tau)
        return a * y + (1.0 - a) * y_target

    def _apply_disturbances(self) -> None:
        """
        Advance any active reservoir / fluid disturbances by one interval.

        ``self.disturbances`` is a list of callables ``f(sim, t)`` applied every
        step, plus the continuous decline rate ``Pr_decline``.
        """
        if self.p.Pr_decline:
            self.p.Pr -= self.p.Pr_decline * self.Ts
        for fn in self.disturbances:
            fn(self, self.t)

    def _log(self) -> None:
        self.history.append(
            {
                "Time_hr": self.t,
                "Choke_pct": self.u,
                "OilRate_bbl_hr": self.Q,
                "WHP_psi": self.WHP,
                "FLP_psi": self.FLP,
                "BHP_psi": self.BHP,
                "WHT_F": self.WHT,
                "AP_psi": self.AP,
                "Pr_psi": self.p.Pr,
                "water_cut": self.p.water_cut,
            }
        )

    # -- public API -----------------------------------------------------------

    def step(self, choke_position: float) -> tuple[float, float, float, float]:
        """
        Apply ``choke_position`` [%] and advance the plant by one control
        interval.  Returns the measured ``(Q, WHP, FLP, BHP)``.
        """
        u_cmd = float(np.clip(choke_position, self.p.u_min, self.p.u_max))

        # Actuator ramp-rate limit is enforced by the plant as well as by the
        # controller, so an aggressive controller cannot cheat.
        if self.enforce_ramp:
            du = np.clip(u_cmd - self.u, -self.p.du_max, self.p.du_max)
            self.u = self.u + du
        else:
            self.u = u_cmd

        # ---- apply time-varying disturbances before solving the plant -----
        self._apply_disturbances()

        ss = steady_state(self.u, self.p)
        # produced OIL rate falls as water cut rises: the well lifts the same
        # total liquid, but a growing fraction of it is water
        ss["Q"] = ss["Q"] * (1.0 - self.p.water_cut)

        self.Q = self._lag(self.Q, ss["Q"], self.p.tau_Q)
        self.WHP = self._lag(self.WHP, ss["WHP"], self.p.tau_WHP)
        self.BHP = self._lag(self.BHP, ss["BHP"], self.p.tau_BHP)

        # FLP carries a small transport delay before its own lag
        self._flp_delay_buffer.append(ss["FLP"])
        n_delay = max(int(round(self.p.theta_FLP / self.Ts)), 0)
        flp_target = self._flp_delay_buffer[max(len(self._flp_delay_buffer) - 1 - n_delay, 0)]
        self.FLP = self._lag(self.FLP, flp_target, self.p.tau_FLP)

        # monitored variables: temperature lags the flow, and annulus pressure
        # follows temperature
        self.WHT = self._lag(self.WHT, ss["WHT"], self.p.tau_WHT)
        self.AP = annulus_pressure(self.WHT, self.p)

        self.t += self.Ts
        self._log()

        if self.noise:
            return (
                self.Q + self.rng.normal(0, self.p.noise_Q),
                self.WHP + self.rng.normal(0, self.p.noise_WHP),
                self.FLP + self.rng.normal(0, self.p.noise_FLP),
                self.BHP + self.rng.normal(0, self.p.noise_BHP),
            )
        return self.Q, self.WHP, self.FLP, self.BHP

    def measure(self) -> tuple[float, float, float, float]:
        """Current measurement without advancing time."""
        if self.noise:
            return (
                self.Q + self.rng.normal(0, self.p.noise_Q),
                self.WHP + self.rng.normal(0, self.p.noise_WHP),
                self.FLP + self.rng.normal(0, self.p.noise_FLP),
                self.BHP + self.rng.normal(0, self.p.noise_BHP),
            )
        return self.Q, self.WHP, self.FLP, self.BHP

    def dataframe(self) -> "pd.DataFrame":
        """Full logged history of the run as a DataFrame."""
        import pandas as pd

        return pd.DataFrame(self.history)


