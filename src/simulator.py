_SS_TABLE_CACHE: dict = {}


def steady_state_table(u_grid=None, params: WellParameters | None = None):
    """
    Steady-state (Q, WHP, FLP, BHP) over a choke grid, cached.

    The plant's steady-state map is independent of the operating limits, so this
    is computed once and reused when scoring many candidate envelopes.
    """
    params = params or WellParameters()
    u_grid = np.arange(0.0, 100.05, 0.05) if u_grid is None else np.asarray(u_grid, float)
    key = (round(params.Pr, 6), round(params.PI, 8), round(params.water_cut, 6),
           len(u_grid), float(u_grid[0]), float(u_grid[-1]))
    hit = _SS_TABLE_CACHE.get(key)
    if hit is not None and len(hit["u"]) == len(u_grid):
        return hit
    rows = [steady_state(float(u), params) for u in u_grid]
    tbl = {"u": u_grid,
           "Q": np.array([r["Q"] for r in rows]) * (1.0 - params.water_cut),
           "WHP": np.array([r["WHP"] for r in rows]),
           "FLP": np.array([r["FLP"] for r in rows]),
           "BHP": np.array([r["BHP"] for r in rows]),
           "WHT": np.array([r["WHT"] for r in rows]),
           "AP": np.array([r["AP"] for r in rows])}
    _SS_TABLE_CACHE[key] = tbl
    return tbl


def envelope_scan(
    env: OperatingEnvelope | None = None,
    params: WellParameters | None = None,
    u_grid: np.ndarray | None = None,
):
    """
    Sweep the choke over its full range and report, for each opening, the
    steady-state operating point and which constraints (if any) are violated.
    """
    import pandas as pd

    env = env or OperatingEnvelope.load()
    params = params or WellParameters()
    u_grid = np.arange(0.0, 100.5, 0.5) if u_grid is None else u_grid

    rows = []
    for u in u_grid:
        ss = steady_state(float(u), params)
        v = env.violations(ss["WHP"], ss["FLP"], ss["BHP"])
        rows.append(
            {
                "Choke_pct": u,
                "Q": ss["Q"],
                "WHP": ss["WHP"],
                "FLP": ss["FLP"],
                "BHP": ss["BHP"],
                "WHT": ss["WHT"],
                "AP": ss["AP"],
                "feasible": len(v) == 0,
                "violations": ",".join(v),
            }
        )
    return pd.DataFrame(rows)


def max_safe_rate(env: OperatingEnvelope | None = None,
                  params: WellParameters | None = None,
                  strict: bool = True):
    """
    Maximum achievable oil rate that keeps every variable inside the envelope.

    Also reports which limit is binding at that point - useful because the
    binding constraint changes with the limit set, and a controller that only
    ever handles one of them is not really constrained control.

    ``strict=False`` returns ``None`` instead of raising when the envelope admits
    no feasible operating point (used when scoring randomised envelopes).
    """
    env = env or OperatingEnvelope.load()
    t = steady_state_table(params=params)
    feas = ((t["WHP"] >= env.WHP_min) & (t["WHP"] <= env.WHP_max)
            & (t["FLP"] >= env.FLP_min) & (t["FLP"] <= env.FLP_max)
            & (t["BHP"] >= env.BHP_min) & (t["BHP"] <= env.BHP_max))
    if not feas.any():
        if strict:
            raise RuntimeError("No feasible operating point exists for this envelope.")
        return None
    idx = np.where(feas)[0]
    j = idx[int(np.argmax(t["Q"][idx]))]

    # which limit is active at the maximum-rate point?
    margins = {"WHP_min": t["WHP"][j] - env.WHP_min, "WHP_max": env.WHP_max - t["WHP"][j],
               "FLP_min": t["FLP"][j] - env.FLP_min, "FLP_max": env.FLP_max - t["FLP"][j],
               "BHP_min": t["BHP"][j] - env.BHP_min, "BHP_max": env.BHP_max - t["BHP"][j]}
    # normalise by each variable's span so the comparison is dimensionless
    spans = {"WHP": env.WHP_max - env.WHP_min, "FLP": env.FLP_max - env.FLP_min,
             "BHP": env.BHP_max - env.BHP_min}
    binding = min(margins, key=lambda k: margins[k] / spans[k.split("_")[0]])

    return {
        "u": float(t["u"][j]), "Q": float(t["Q"][j]),
        "WHP": float(t["WHP"][j]), "FLP": float(t["FLP"][j]), "BHP": float(t["BHP"][j]),
        "binding": binding,
        "u_min_feasible": float(t["u"][idx].min()),
        "u_max_feasible": float(t["u"][idx].max()),
        "Q_min_feasible": float(t["Q"][idx].min()),
    }
