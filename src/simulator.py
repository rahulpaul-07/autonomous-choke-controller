"""
simulator.py
================================================================================
Physics-structured dynamic simulator for a single naturally flowing oil well
with one production choke.

Honeywell Campus Connect - Autonomous Production Choke Controller

Model structure (steady state is solved from first principles, dynamics are
first-order lags identified from step-test data):

    1. Reservoir inflow (linear IPR)      Q  = PI * (Pr - BHP)
    2. Tubing lift performance (VLP)      WHP = BHP - dP_tubing(Q)
    3. Production choke (orifice eqn)     Q  = CdA(u) * sqrt(WHP - FLP)
    4. Gathering manifold back-pressure   FLP = f(u)      (empirical, calibrated)

The four equations are solved simultaneously for (Q, BHP, WHP) at every
steady state; the transient response is generated by applying an independent
first-order lag to each measured variable, with time constants identified from
the reference step-test data.

Assumptions (per challenge statement)
    * single naturally flowing well, single production choke
    * no gas lift / no ESP / no artificial lift
    * no facility network interaction (manifold treated as a calibrated
      back-pressure boundary condition)
    * constant reservoir properties, constant GOR and water cut
    * choke opening u [%] is the only manipulated variable
    * control interval Ts = 1 hour
================================================================================
"""

from __future__ import annotations

import json
import os
import warnings
from dataclasses import dataclass, field, replace

import numpy as np
from scipy.optimize import brentq

# ------------------------------------------------------------------------------
# Physical / calibrated parameters
# ------------------------------------------------------------------------------


@dataclass
class WellParameters:
    """Physical parameters of the well, calibrated against the reference dataset."""

    # --- Reservoir inflow performance (IPR) -----------------------------------
    Pr: float = 3568.8          # average reservoir pressure                [psi]
    PI: float = 0.2313          # productivity index              [bbl/hr per psi]

    # --- Tubing lift performance (VLP): dP_tub = t0 + t1*Q + t2*Q^2 ----------
    # In this rate window the gas-lightening of the column dominates wall
    # friction, so the tubing pressure loss falls as rate increases.
    t0: float = 3297.5
    t1: float = -4.8470
    t2: float = 0.0055350

    # --- Production choke characteristic: CdA(u) = c0 + c1*u + c2*u^2 --------
    # Effective discharge coefficient x flow area, [bbl/hr / sqrt(psi)]
    c0: float = 3.7870
    c1: float = 0.184000
    c2: float = 0.00105630

    # --- Gathering-manifold back-pressure: FLP = m0 + m1*u + m2*u^2 ----------
    m0: float = 212.513
    m1: float = -0.69230
    m2: float = -0.0029900

    # --- Dynamics: first-order time constants identified from step tests -----
    tau_Q: float = 5.89         # oil rate settling time constant             [h]
    tau_WHP: float = 9.82       # wellhead pressure time constant             [h]
    tau_FLP: float = 6.79       # flowline pressure time constant             [h]
    tau_BHP: float = 13.53      # bottom-hole pressure time constant          [h]
    tau_WHT: float = 20.0       # wellhead temperature - thermal, so slowest   [h]
    theta_FLP: float = 0.24     # small transport delay on FLP                [h]

    # --- Actuator ------------------------------------------------------------
    u_min: float = 0.0          # choke fully closed                          [%]
    u_max: float = 100.0        # choke fully open                            [%]
    du_max: float = 5.0         # ramp-rate limit per control interval        [%]

    # --- Informational variables (monitored, NOT active constraints) ---------
    # The brief names WHT and annulus pressure as variables that "should be
    # recognised as part of a complete production operating envelope".
    T_res: float = 200.0        # reservoir / bottom-hole temperature         [F]
    T_amb: float = 80.0         # ambient temperature at surface              [F]
    wht_a: float = 69.3         # heat-loss group; higher rate -> hotter wellhead
    AP_ref: float = 250.0       # annulus pressure at the reference WHT      [psi]
    WHT_ref: float = 140.0      # reference wellhead temperature              [F]
    AP_dPdT: float = 3.5        # annular thermal pressure buildup      [psi / F]

    # --- Reservoir / fluid disturbances (all OFF by default; the challenge
    #     assumes constant reservoir properties. These exist so we can TEST
    #     what happens when that assumption is violated.)
    Pr_decline: float = 0.0     # reservoir pressure decline rate       [psi/h]
    water_cut: float = 0.0      # fraction of liquid that is water         [-]

    # --- Measurement noise (1 sigma), representative of field instrumentation
    noise_Q: float = 0.60       # [bbl/hr]
    noise_WHP: float = 0.50     # [psi]
    noise_FLP: float = 0.45     # [psi]
    noise_BHP: float = 2.50     # [psi]


# Location of the editable limits file. The official safe operating ranges were
# NOT published with the problem statement; every numeric limit lives in this one
# file so the official values can be dropped in without touching any code.
LIMITS_FILE = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "config", "operating_limits.json")


@dataclass
class OperatingEnvelope:
    """
    Safe operating envelope - the hard constraints the controller must respect.

    Defaults mirror ``config/operating_limits.json``. Prefer
    :meth:`OperatingEnvelope.load` so that editing that file is enough to adopt
    a different (or the official) set of limits.
    """

    WHP_min: float = 200.0      # slugging / flowline entry limit            [psi]
    WHP_max: float = 320.0      # wellhead equipment rating                  [psi]
    FLP_min: float = 140.0      # minimum transport pressure to separator    [psi]
    FLP_max: float = 210.0      # gathering system rating                    [psi]
    BHP_min: float = 2850.0     # max drawdown: sand / bubble-point limit    [psi]
    BHP_max: float = 3300.0     # minimum drawdown for stable inflow         [psi]

    source: str = "built-in defaults"

    # -- loading / saving ----------------------------------------------------

    @classmethod
    def load(cls, path: str | None = None, quiet: bool = True) -> "OperatingEnvelope":
        """
        Build an envelope from ``config/operating_limits.json``.

        Falls back to the built-in defaults (with a warning) if the file is
        missing or malformed, so nothing ever fails silently on a bad edit.
        """
        path = path or LIMITS_FILE
        try:
            with open(path) as f:
                cfg = json.load(f)
            lim = cfg["limits"]
            env = cls(**{k: float(v["value"]) for k, v in lim.items()},
                      source=os.path.basename(path))
        except (OSError, KeyError, TypeError, ValueError) as exc:
            warnings.warn(f"could not read limits from {path} ({exc}); "
                          f"using built-in defaults", RuntimeWarning)
            return cls()
        env.validate()
        if not quiet:
            print(env.describe())
        return env

    def validate(self) -> None:
        """Reject an envelope that is empty or inverted."""
        for tag in ("WHP", "FLP", "BHP"):
            lo, hi = getattr(self, f"{tag}_min"), getattr(self, f"{tag}_max")
            if not hi > lo:
                raise ValueError(f"{tag} limits are inverted or empty: [{lo}, {hi}]")

    def describe(self) -> str:
        """Human-readable summary of the envelope and where it was loaded from."""
        return ("Operating envelope (source: %s)\n" % self.source
                + "\n".join(f"    {t:3s}  {getattr(self, t+'_min'):8.1f} – "
                             f"{getattr(self, t+'_max'):8.1f} psi"
                             for t in ("WHP", "FLP", "BHP")))

    def violations(self, WHP: float, FLP: float, BHP: float) -> list[str]:
        """Return a list of constraint names violated by this operating point."""
        v = []
        if WHP < self.WHP_min:
            v.append("WHP_min")
        if WHP > self.WHP_max:
            v.append("WHP_max")
        if FLP < self.FLP_min:
            v.append("FLP_min")
        if FLP > self.FLP_max:
            v.append("FLP_max")
        if BHP < self.BHP_min:
            v.append("BHP_min")
        if BHP > self.BHP_max:
            v.append("BHP_max")
        return v

    def is_feasible(self, WHP: float, FLP: float, BHP: float) -> bool:
        """True when this operating point is inside every limit."""
        return not self.violations(WHP, FLP, BHP)


# ------------------------------------------------------------------------------
# Steady-state solver
# ------------------------------------------------------------------------------


def choke_CdA(u: float, p: WellParameters) -> float:
    """Effective choke discharge coefficient x area as a function of opening."""
    u = float(np.clip(u, p.u_min, p.u_max))
    return max(p.c0 + p.c1 * u + p.c2 * u**2, 1e-3)


def flowline_pressure(u: float, p: WellParameters) -> float:
    """Gathering-manifold back-pressure downstream of the choke."""
    u = float(np.clip(u, p.u_min, p.u_max))
    return p.m0 + p.m1 * u + p.m2 * u**2


def tubing_dp(Q: float, p: WellParameters) -> float:
    """Total tubing pressure loss (hydrostatic + friction) at rate Q."""
    return p.t0 + p.t1 * Q + p.t2 * Q**2


def wellhead_temperature(Q: float, p: WellParameters | None = None) -> float:
    """
    Wellhead temperature from a Ramey-type heat-loss argument.

    Produced fluid leaves the reservoir at ``T_res`` and loses heat to the
    formation on the way up. The faster it flows, the less time it spends in the
    tubing, so the HOTTER it arrives at surface:

        WHT = T_amb + (T_res - T_amb) * exp(-a / Q)

    As Q -> 0 the fluid equilibrates with the surroundings; as Q -> inf it
    arrives at reservoir temperature.
    """
    p = p or WellParameters()
    Q = max(float(Q), 1e-3)
    return p.T_amb + (p.T_res - p.T_amb) * float(np.exp(-p.wht_a / Q))


def annulus_pressure(WHT: float, p: WellParameters | None = None) -> float:
    """
    Annulus pressure from annular thermal expansion (APB).

    In a packer-completed well the A-annulus is sealed, so its pressure is
    driven mainly by the temperature of the fluid it contains rather than by the
    production pressures. Heating the tubing heats the trapped annular fluid,
    which cannot expand, so the pressure rises.

    This is why annulus pressure is a WELL-INTEGRITY variable rather than a
    production one - and why it moves in the OPPOSITE direction to WHP, FLP and
    BHP as the choke opens.
    """
    p = p or WellParameters()
    return p.AP_ref + p.AP_dPdT * (float(WHT) - p.WHT_ref)


def steady_state(u: float, p: WellParameters | None = None) -> dict:
    """
    Solve the coupled IPR / VLP / choke system for the steady state at choke
    opening ``u``.

    Returns dict with keys Q, WHP, FLP, BHP.
    """
    p = p or WellParameters()
    FLP = flowline_pressure(u, p)
    CdA = choke_CdA(u, p)

    def residual(Q: float) -> float:
        """Choke-equation mismatch at rate ``Q``; zero at the solution."""
        BHP = p.Pr - Q / p.PI
        WHP = BHP - tubing_dp(Q, p)
        dP = WHP - FLP
        if dP <= 0.0:
            # Choke would be starved: return a large positive residual so the
            # root finder is pushed back towards lower rate.
            return Q + abs(dP)
        return Q - CdA * np.sqrt(dP)

    # Bracket the physical root. Residual is monotonically increasing in Q over
    # the well's stable operating branch.
    lo, hi = 1.0, 400.0
    f_lo, f_hi = residual(lo), residual(hi)
    if f_lo * f_hi > 0:
        # Expand / fall back to a coarse scan if the default bracket fails.
        grid = np.linspace(1.0, 500.0, 2000)
        vals = np.array([residual(q) for q in grid])
        sign_change = np.where(np.sign(vals[:-1]) != np.sign(vals[1:]))[0]
        if len(sign_change) == 0:
            Q = float(grid[np.argmin(np.abs(vals))])
            BHP = p.Pr - Q / p.PI
            WHT = wellhead_temperature(Q, p)
            return {"Q": Q, "WHP": BHP - tubing_dp(Q, p), "FLP": FLP, "BHP": BHP,
                    "WHT": WHT, "AP": annulus_pressure(WHT, p)}
        lo, hi = grid[sign_change[0]], grid[sign_change[0] + 1]

    Q = brentq(residual, lo, hi, xtol=1e-8)
    BHP = p.Pr - Q / p.PI
    WHP = BHP - tubing_dp(Q, p)
    WHT = wellhead_temperature(Q, p)
    return {"Q": float(Q), "WHP": float(WHP), "FLP": float(FLP), "BHP": float(BHP),
            "WHT": WHT, "AP": annulus_pressure(WHT, p)}


